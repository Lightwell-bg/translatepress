<?php
/**
 * Какие адреса ссылок имеет смысл переводить.
 *
 * @package WpMlp
 */

declare(strict_types=1);

namespace WpMlp\Rendering;

/**
 * Решает, стоит ли заводить `href` как отдельную строку словаря.
 *
 * Своя проверка, а не общая {@see \WpMlp\Support\Text::isTranslatable()}:
 * та написана про прозу и на адресах отвечает как придётся. Она,
 * например, отвергает `https://site.ru/x/` как «похожее на URL», но
 * пропускает `/blog/x/` — то есть одна и та же ссылка попадала бы в
 * словарь или нет в зависимости от того, записал её автор полностью или
 * относительным путём. Здесь правило про адреса и сформулировано как
 * правило про адреса.
 *
 * Что отсекается и почему:
 *
 * - `mailto:`, `tel:`, `javascript:`, `data:` — это не страницы, языковой
 *   версии у них не бывает;
 * - голый якорь (`#comments`) — ссылка на место внутри ЭТОЙ же страницы,
 *   которая уже переведена целиком;
 * - пустой `href` — ничего не адресует.
 *
 * Внешние домены НЕ отсекаются намеренно: ссылка на англоязычную
 * документацию вполне может иметь болгарский аналог, и запрещать это
 * значило бы решать за владельца сайта. Объём списка держит в узде
 * отдельная вкладка «Ссылки», а не запрет.
 */
final class LinkTarget {

	/**
	 * Схемы, за которыми нет страницы с языковыми версиями.
	 */
	private const NON_PAGE_SCHEMES = array( 'mailto', 'tel', 'javascript', 'data', 'sms', 'ftp' );

	/**
	 * Сегменты пути, за которыми стоит служебная часть WordPress, а не
	 * контент.
	 *
	 * Найдено на живом сайте: ссылка «Выйти» и «Редактировать» в форме
	 * комментариев видна только вошедшему администратору и ведёт на
	 * `/wp-login.php?action=logout` или `/wp-admin/post.php?action=edit`.
	 * У административного адреса не бывает языковой версии в принципе —
	 * его переводить в смысле «направить на другую страницу» нечем, а в
	 * словаре такая строка — чистый шум, который к тому же виден только
	 * администратору и никогда — обычному посетителю.
	 */
	private const ADMIN_PATH_PATTERN = '#/(wp-admin/|wp-login\.php)#i';

	/**
	 * Максимальная длина адреса, который мы готовы хранить.
	 *
	 * Колонка `source_text` — TEXT, но адреса длиннее пары килобайт это,
	 * как правило, data-URI или трекинговые простыни, которые никто не
	 * будет переводить руками.
	 */
	private const MAX_LENGTH = 2000;

	/**
	 * Стоит ли заводить этот адрес в словарь. Чистая функция.
	 *
	 * @param string $href Значение атрибута `href` как есть.
	 */
	public static function isTranslatable( string $href ): bool {
		$href = trim( $href );

		if ( '' === $href || strlen( $href ) > self::MAX_LENGTH ) {
			return false;
		}

		// Якорь внутри текущей страницы: отдельного адреса за ним нет.
		if ( str_starts_with( $href, '#' ) ) {
			return false;
		}

		$scheme = self::scheme( $href );

		if ( '' !== $scheme && in_array( $scheme, self::NON_PAGE_SCHEMES, true ) ) {
			return false;
		}

		$path = self::path( $href );

		return 1 !== preg_match( self::ADMIN_PATH_PATTERN, $path );
	}

	/**
	 * Приводит адрес к виду, в котором он ложится в словарь.
	 *
	 * Только обрезка краёв: внутри адреса пробелов быть не должно, а
	 * схлопывать что-либо ещё (как делает Text::normalize() с прозой)
	 * нельзя — любой изменённый символ ведёт уже на другую страницу.
	 *
	 * @param string $href Значение атрибута `href`.
	 */
	public static function normalize( string $href ): string {
		return trim( $href );
	}

	/**
	 * Схема адреса в нижнем регистре, либо пустая строка. Чистая функция.
	 *
	 * Разбирается вручную, а не через `wp_parse_url()`: тот на мусорных
	 * значениях возвращает false, и отличить «схемы нет» от «адрес битый»
	 * становится нельзя.
	 *
	 * @param string $href Значение атрибута `href`.
	 */
	private static function scheme( string $href ): string {
		if ( str_starts_with( $href, '//' ) ) {
			// Протокол-относительный адрес: схема совпадает со схемой страницы.
			return '';
		}

		$colon = strpos( $href, ':' );

		if ( false === $colon || 0 === $colon ) {
			return '';
		}

		$candidate = substr( $href, 0, $colon );

		// Схема — буквы, цифры, `+`, `-`, `.`, начиная с буквы (RFC 3986).
		if ( 1 !== preg_match( '/^[A-Za-z][A-Za-z0-9+.\-]*$/', $candidate ) ) {
			// Двоеточие внутри пути, а не разделитель схемы.
			return '';
		}

		return strtolower( $candidate );
	}

	/**
	 * Путь адреса, с ведущим слешем, без хвостового `?query#fragment`.
	 *
	 * Разбирается вручную вместе со `scheme()` по той же причине:
	 * `wp_parse_url()` на относительном пути без схемы иногда путает путь с
	 * именем хоста, а здесь нужен именно кусок ДО `?` и `#`, каким бы ни
	 * было начало строки.
	 *
	 * @param string $href Значение атрибута `href`.
	 */
	private static function path( string $href ): string {
		$path = (string) preg_replace( '/[?#].*$/', '', $href );

		// Слеш нужен, чтобы `wp-admin` в имени страницы не спутать с сегментом пути.
		return '/' === substr( $path, -1 ) ? $path : $path . '/';
	}
}
